import { useAdminAuth } from '@/contexts/AdminAuthContext';
import {
  LayoutDashboard,
  Package,
  ShoppingCart,
  Home,
  Settings,
  LogOut,
  Menu,
  X,
  Tag,
  Bell,
  Search,
  User,
  FileText,
  BarChart3,
  Shield,
  ChevronDown,
  CreditCard,
  Mail,
  RefreshCw
} from 'lucide-react';
